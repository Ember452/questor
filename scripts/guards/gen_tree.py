#!/usr/bin/env python3
"""Generate or verify the source tree map used by STRUCTURE.md.

``--write`` regenerates ``docs/architecture/TREE.md``; ``--check`` fails when the
committed map is stale, so the document cannot drift away from the code.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

try:
    from ._guard_kit import EXIT_OK, EXIT_RED, count_lines, walk_py
except ImportError:  # direct script execution
    from _guard_kit import EXIT_OK, EXIT_RED, count_lines, walk_py

REPO_ROOT = Path(__file__).resolve().parents[2]
TARGET = REPO_ROOT / "docs/architecture/TREE.md"
ROOTS = ("src/questorharness", "src/questor")


def render(root: Path) -> str:
    lines = [
        "# Source tree map",
        "",
        "Generated by `scripts/guards/gen_tree.py`. Do not edit by hand;",
        "run `uv run python scripts/guards/gen_tree.py --write` instead.",
        "",
    ]
    for source in ROOTS:
        base = root / source
        if not base.is_dir():
            continue
        lines.append(f"## {source}")
        lines.append("")
        lines.append("| module | lines |")
        lines.append("| --- | ---: |")
        for path in walk_py(base):
            relative = path.relative_to(root).as_posix()
            lines.append(f"| `{relative}` | {count_lines(path)} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite the tree map")
    parser.add_argument("--check", action="store_true", help="fail when the map is stale")
    args = parser.parse_args(argv)

    generated = render(REPO_ROOT)
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(generated, encoding="utf-8", newline="\n")
        print(f"tree map written: {TARGET.relative_to(REPO_ROOT)}")
        return EXIT_OK

    if not TARGET.exists():
        print(f"tree map missing: {TARGET.relative_to(REPO_ROOT)}", file=sys.stderr)
        return EXIT_RED
    current = TARGET.read_text(encoding="utf-8")
    if current != generated:
        print(
            "tree map is stale; run `uv run python scripts/guards/gen_tree.py --write`",
            file=sys.stderr,
        )
        return EXIT_RED
    print("tree map: OK (up to date)")
    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
