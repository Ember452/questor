#!/usr/bin/env python3
"""Generate docs/architecture/GRAPH.md (plan 01, W6).

The document is generated, never edited: ``--check`` fails on any difference,
which is also how the *frozen* indirect entries work. The freeze is the content
of the file: a sixth ``capabilities -> execution`` edge, a second reverse edge or
a new vacuous contract all change the rendering, so the check goes red and the
change has to be reviewed instead of slipping in.

Sections: package graph, cycles, most-imported modules with kind labels,
over-threshold files, vacuous contracts, capability radius, frozen entries.

Usage:
    uv run python scripts/guards/gen_graph.py --write
    uv run python scripts/guards/gen_graph.py --check
"""

from __future__ import annotations

import argparse
import ast
import configparser
import sys
from collections import Counter, defaultdict
from collections.abc import Iterable, Sequence
from pathlib import Path

try:
    from ._guard_kit import count_lines, read_text, tracked_files
except ImportError:  # direct script execution
    from _guard_kit import count_lines, read_text, tracked_files

REPO_ROOT = Path(__file__).resolve().parents[2]
TARGET = REPO_ROOT / "docs/architecture/GRAPH.md"
HEADER = "<!-- generated by scripts/guards/gen_graph.py; do not edit -->"

BANNED = {
    "base.py",
    "manager.py",
    "types.py",
    "constants.py",
    "helpers.py",
    "service.py",
    "utils.py",
    "common.py",
    "core.py",
    "misc.py",
    "handler.py",
    "processor.py",
}
SOFT_LINE_LIMIT = 1000
DIR_FANOUT_WARN = 17
TOP_IMPORTED = 10
CAPABILITY_FILES = ("src/questorharness/capabilities/tools/registry.py",)


def _module(path: Path, root: Path) -> str:
    parts = path.relative_to(root).with_suffix("").parts[1:]
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _package(module: str) -> str:
    parts = module.split(".")
    return ".".join(parts[:2]) if len(parts) > 1 else parts[0]


def _imports(path: Path, module: str) -> Iterable[str]:
    is_package = path.name == "__init__.py"
    package_parts = module.split(".") if is_package else module.split(".")[:-1]
    tree = ast.parse(read_text(path))
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                yield alias.name
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                base = package_parts
                if node.level > 1:
                    base = package_parts[: len(package_parts) - (node.level - 1)]
                parts = [*base]
                if node.module:
                    parts.extend(node.module.split("."))
                yield ".".join(parts)
            elif node.module:
                yield node.module


def _sccs(nodes: set[str], edges: dict[str, set[str]]) -> list[list[str]]:
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    stack: list[str] = []
    on_stack: set[str] = set()
    result: list[list[str]] = []
    counter = [0]

    def visit(node: str) -> None:
        index[node] = low[node] = counter[0]
        counter[0] += 1
        stack.append(node)
        on_stack.add(node)
        for neighbour in sorted(edges.get(node, ())):
            if neighbour not in index:
                visit(neighbour)
                low[node] = min(low[node], low[neighbour])
            elif neighbour in on_stack:
                low[node] = min(low[node], index[neighbour])
        if low[node] == index[node]:
            component: list[str] = []
            while True:
                item = stack.pop()
                on_stack.discard(item)
                component.append(item)
                if item == node:
                    break
            if len(component) > 1:
                result.append(sorted(component))

    for node in sorted(nodes):
        if node not in index:
            visit(node)
    return result


def _registered_edges(root: Path) -> set[tuple[str, str]]:
    """Return the reverse edges registered in ``.importlinter`` ignore_imports."""
    parser = configparser.ConfigParser()
    parser.read(root / ".importlinter", encoding="utf-8")
    registered: set[tuple[str, str]] = set()
    for section in parser.sections():
        raw = parser[section].get("ignore_imports", "")
        for line in raw.splitlines():
            if "->" not in line:
                continue
            source, _, target = line.partition("->")
            registered.add((_package(source.strip()), _package(target.strip())))
    return registered


def _cycle_label(component: list[str], edges: dict[str, set[str]], registered: set[tuple[str, str]]) -> str:
    """A cycle is registered when one of its edges is a declared reverse edge."""
    for source in component:
        for target in edges.get(source, ()):
            if target in component and (source, target) in registered:
                return "已登记"
    return "**未登记**"


def _vacuous_contracts(root: Path) -> list[str]:
    parser = configparser.ConfigParser()
    parser.read(root / ".importlinter", encoding="utf-8")
    vacuous: list[str] = []
    for section in parser.sections():
        if not section.startswith("importlinter:contract:"):
            continue
        name = parser[section].get("name", section)
        targets: list[str] = []
        for key in ("source_modules", "forbidden_modules", "layers"):
            raw = parser[section].get(key, "")
            targets.extend(line.strip() for line in raw.splitlines() if line.strip())
        for target in targets:
            relative = Path("src") / Path(*target.split("."))
            if not relative.with_suffix(".py").exists() and not relative.is_dir():
                vacuous.append(f"`{target}` (declared by {name})")
    return sorted(set(vacuous))


def _kind(relative: str) -> str:
    name = Path(relative).name
    if name == "__init__.py":
        return "门面"
    if name in BANNED:
        return f"禁用名 {name}"
    return "契约/原语/实现"


def render(root: Path) -> str:
    files = tracked_files(root, ("src",))
    modules = {path: _module(path, root) for path in files}
    packages = sorted({_package(module) for module in modules.values() if module})
    edges: dict[str, set[str]] = {package: set() for package in packages}
    in_degree: Counter[str] = Counter()
    file_in: Counter[str] = Counter()
    file_edges: dict[str, set[str]] = defaultdict(set)

    for path, module in modules.items():
        source = _package(module)
        for imported in _imports(path, module):
            if not (imported.startswith("questorharness") or imported.startswith("questor")):
                continue
            target = _package(imported)
            if target == source or target not in edges:
                continue
            edges[source].add(target)
            in_degree[target] += 1
            file_edges[module].add(imported)
            file_in[imported] += 1

    lines = [
        "# Dependency graph",
        "",
        HEADER,
        "",
        "本文件由 `scripts/guards/gen_graph.py` 生成，**禁止手改**；`--check` 逐字比对，",
        "任何差异（多一条边、多一个环、多一条恒真契约）都会让它变红。",
        "",
        "## 包级邻接表",
        "",
        "| package | imports |",
        "| --- | --- |",
    ]
    for package in packages:
        targets = ", ".join(f"`{target}`" for target in sorted(edges[package])) or "—"
        lines.append(f"| `{package}` | {targets} |")

    cycles = _sccs(set(packages), edges)
    registered = _registered_edges(root)
    unregistered = [item for item in cycles if _cycle_label(item, edges, registered) == "**未登记**"]
    lines += [
        "",
        "## 环",
        "",
        f"包级环数：**{len(cycles)}**（已登记 {len(cycles) - len(unregistered)} / 未登记 {len(unregistered)}）",
        "",
        "已登记的环来自 `.importlinter` 的 `ignore_imports`（一条反向边）；未登记即新增环，必须修。",
        "",
    ]
    if cycles:
        for component in cycles:
            label = _cycle_label(component, edges, registered)
            lines.append(f"- {' <-> '.join(f'`{item}`' for item in component)}（{label}）")
    else:
        lines.append("- 无")

    lines += [
        "",
        "## 被 import 最多的模块（Top10）",
        "",
        "`类型` 栏是共享点仪表盘：`禁用名` 类文件挤回 Top10，说明共享点又在膨胀。",
        "",
        "| module | imported by | 类型 |",
        "| --- | ---: | --- |",
    ]
    top = sorted(file_in.items(), key=lambda item: (-item[1], item[0]))[:TOP_IMPORTED]
    for module, degree in top:
        lines.append(f"| `{module}` | {degree} | {_kind(module.replace('.', '/') + '.py')} |")

    over = [
        (count_lines(path), path.relative_to(root).as_posix())
        for path in files
        if count_lines(path) > SOFT_LINE_LIMIT
    ]
    fanout: Counter[str] = Counter()
    for path in files:
        if path.name != "__init__.py":
            fanout[path.parent.relative_to(root).as_posix()] += 1
    wide = sorted((name, count) for name, count in fanout.items() if count >= DIR_FANOUT_WARN)
    lines += ["", "## 超阈值清单", "", "### 文件（>1000 行）", ""]
    if over:
        for line_count, relative in sorted(over, reverse=True):
            lines.append(f"- `{relative}`: {line_count} lines")
    else:
        lines.append("- 无")
    lines += ["", f"### 目录（>={DIR_FANOUT_WARN} 个非 init 源文件）", ""]
    if wide:
        for name, count in sorted(wide, key=lambda item: (-item[1], item[0])):
            lines.append(f"- `{name}`: {count} files")
    else:
        lines.append("- 无")

    vacuous = _vacuous_contracts(root)
    lines += [
        "",
        "## vacuous-contracts",
        "",
        f"目标模块不存在、因而恒判 KEPT 的契约目标：**{len(vacuous)}**",
        "",
    ]
    if vacuous:
        lines.extend(f"- {item}" for item in vacuous)
    else:
        lines.append("- 无")

    radius = [relative for relative in CAPABILITY_FILES if (root / relative).exists()]
    lines += [
        "",
        "## 新增能力半径",
        "",
        f"新增一个工具需要改动的共享文件：**{len(radius)}**",
        "",
    ]
    lines.extend(f"- `{relative}`" for relative in radius)

    frozen_execution = sorted(
        f"`{module}` -> `{target}`"
        for module, targets in file_edges.items()
        if module.startswith("questorharness.capabilities")
        for target in targets
        if target.startswith("questorharness.execution")
    )
    frozen_providers = sorted(
        {
            target
            for module, targets in file_edges.items()
            if module.startswith("questorharness.execution")
            for target in targets
            if target.startswith("questorharness.providers")
        }
    )
    reverse = sorted(
        f"`{module}` -> `{target}`"
        for module, targets in file_edges.items()
        if module.startswith("questorharness.runtime")
        for target in targets
        if target.startswith("questorharness.engine")
    )
    lines += [
        "",
        "## 冻结的间接入口",
        "",
        "`capabilities-are-leaf` 仍保留 `allow_indirect_imports`：下面的边是**登记的例外**，",
        "多一条即红；Phase 3 把 sandbox 抽成 Port 后逐条删除。",
        "",
        f"### capabilities -> execution（{len(frozen_execution)} 条）",
        "",
    ]
    lines.extend(f"- {item}" for item in frozen_execution)
    lines += [
        "",
        f"### execution -> providers（模块集，{len(frozen_providers)} 个）",
        "",
    ]
    lines.extend(f"- `{item}`" for item in frozen_providers)
    lines += [
        "",
        f"### runtime -> engine（反向边，{len(reverse)} 条）",
        "",
    ]
    lines.extend(f"- {item}" for item in reverse)
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="rewrite the graph document")
    action.add_argument("--check", action="store_true", help="fail when the document is stale or hand-edited")
    args = parser.parse_args(argv)

    generated = render(REPO_ROOT)
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(generated, encoding="utf-8", newline="\n")
        print(f"graph written: {TARGET.relative_to(REPO_ROOT)}")
        return 0
    if not TARGET.exists():
        print(f"graph missing: {TARGET.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1
    current = TARGET.read_text(encoding="utf-8")
    if current != generated:
        print(
            "dependency graph is stale or hand-edited; run "
            "`uv run python scripts/guards/gen_graph.py --write`",
            file=sys.stderr,
        )
        return 1
    cycles = generated.split("包级环数：**", 1)[-1].split("**", 1)[0]
    unregistered = "未登记 0" if "未登记 0）" in generated else "UNREGISTERED CYCLE PRESENT"
    print(f"graph: OK (cycles: {cycles}; {unregistered})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
