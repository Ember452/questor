"""W5 golden: tool carry-over metadata must not drift.

``tests/fixtures/baseline/tool_metadata_golden.json`` was generated by running the
pre-refactor implementation and the new one over the same matrix and asserting
they agree; the fixture stores both the inputs and the expected metadata, so this
test needs no second copy of the matrix.

Timestamps are normalised to ``0.0`` because ``time.time()`` is not reproducible.
"""

from __future__ import annotations

import json
from pathlib import Path
from types import SimpleNamespace

import pytest

from questorharness.engine.tool_metadata import _record_tool_carryover

FIXTURE = Path(__file__).resolve().parents[2] / "fixtures" / "baseline" / "tool_metadata_golden.json"
CASES = json.loads(FIXTURE.read_text(encoding="utf-8"))["cases"]


def _normalise(value):
    if isinstance(value, dict):
        return {key: _normalise(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_normalise(item) for item in value]
    if isinstance(value, float):
        return 0.0
    return value


def test_fixture_is_not_empty() -> None:
    """A golden table with no cases would pass vacuously."""
    assert len(CASES) >= 10


@pytest.mark.parametrize("case", CASES, ids=[f"{item['case']}-{item['tool']}" for item in CASES])
def test_carry_over_matches_golden(case: dict) -> None:
    metadata: dict[str, object] = {}
    context = SimpleNamespace(tool_metadata=metadata)
    _record_tool_carryover(
        context,
        tool_name=case["tool"],
        tool_input=dict(case["input"]),
        tool_output=case["output"],
        tool_result_metadata=case["meta"],
        is_error=case["error"],
        resolved_file_path=case["path"],
    )
    assert _normalise(metadata) == case["expected"]
